      <p text mt=std>
        "Single-Sign-On" or "Single-Sign-On-Registration or "-Authentication" refers to procedures that allow users to
        use
        a user account to log in to our online offer with their respective account of the Single-Sign-On-Service (e.g. a
        social network like Google). The prerequisite for Single-Sign-On-Authentication is that the user is registered
        with the respective Single-Sign-On-Provider and enters the required access data in the online form provided for
        this purpose, or are already registered with the Single-Sign-On-Provider and confirm the
        Single-Sign-On-Registration via a button through our online offer.
      </p>

      <p text mt=std>
        The authentication takes place directly with the respective Single-Sign-On-Provider. As part of such
        authentication, we receive a user ID with the information that the user is logged in to the respective
        Single-Sign-On-Provider under this user ID and an ID that we can no longer use for other purposes (so-called
        "user
        handle"). Whether additional data is transmitted to us depends solely on the Single-Sign-On-Procedure used, on
        the
        selected data releases as part of the authentication and also on what data users have in the privacy or other
        settings of the user account with the Single-Sign-On-Provider. Depending on the Single-Sign-On-Provider and the
        choice of the user, it can be different data, usually it is the e-mail address, user name and ID. The password
        entered during the sign-on procedure with the Single-Sign-On-Provider is neither visible to us nor is it stored
        by
        us.
      </p>

      <p text mt=std>
        Users are asked to note that their information stored by us can be automatically compared with their user
        account
        with the Single-Sign-On-Provider, but this is not always possible or actually takes place. If, for example, the
        e-mail addresses of the users change, they must change them manually in their user account with us.
      </p>

      <p text mt=std>
        If agreed with the users, we can use the Single-Sign-On-Registration in the context of or before the fulfillment
        of the contract, insofar as the users have been asked to do so, process it within the framework of consent and
        otherwise use it on the basis of our legitimate interests and those of the interests of the users in an
        effective
        and secure registration system.
      </p>

      <p text mt=std>
        If users decide that they no longer want to use the connection to their user account with the single sign-on
        provider for the single sign-on process, they must cancel this connection within their user account with the
        Single-Sign-On-Provider and remove it through the settings panel of our online offer. Note, that options to
        login
        with the Single-Sign-On-Provider to our online offer will no longer be possible and you will need to use the
        e-mail address provided
        by the registration through the Single-Sign-On-Provider to keep loging in. If users want to delete their data
        from
        us, they must
        cancel their registration with us.
      </p>

